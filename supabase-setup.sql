create or replace function public.increment_portfolio_view(p_portfolio_id bigint)
returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare new_view_count bigint;
begin
  update public.portfolios
  set view_count = view_count + 1
  where id = p_portfolio_id and is_published = true
  returning view_count into new_view_count;
  return new_view_count;
end;
$$;
revoke all on function public.increment_portfolio_view(bigint) from public;
grant execute on function public.increment_portfolio_view(bigint) to anon, authenticated;

