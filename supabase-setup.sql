-- Three inquiry attempts per IP fingerprint per 15 minutes. Only the Edge Function can call this.
create table if not exists public.inquiry_rate_limits (
  fingerprint text primary key,
  window_started_at timestamptz not null default now(),
  attempts integer not null default 0
);
alter table public.inquiry_rate_limits enable row level security;
revoke all on public.inquiry_rate_limits from public, anon, authenticated;

create or replace function public.consume_inquiry_limit(p_fingerprint text)
returns boolean
language plpgsql
security definer
set search_path = public
as $$
declare current_attempts integer;
begin
  delete from public.inquiry_rate_limits where window_started_at < now() - interval '24 hours';
  insert into public.inquiry_rate_limits as limits (fingerprint, window_started_at, attempts)
  values (p_fingerprint, now(), 1)
  on conflict (fingerprint) do update set
    attempts = case when limits.window_started_at < now() - interval '15 minutes' then 1 else limits.attempts + 1 end,
    window_started_at = case when limits.window_started_at < now() - interval '15 minutes' then now() else limits.window_started_at end
  returning attempts into current_attempts;
  return current_attempts <= 3;
end;
$$;
revoke all on function public.consume_inquiry_limit(text) from public, anon, authenticated;
grant execute on function public.consume_inquiry_limit(text) to service_role;

